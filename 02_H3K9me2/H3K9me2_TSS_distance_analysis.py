#!/usr/bin/env python3

"""
Distance-to-TSS analyses for delta H3K9me2 and TE expression.

This script consumes the 1-kb table generated by
H3K9me2_TE_correlation.py and performs the remaining
distance analyses:

1. Calculates the distance from every 1-kb genomic bin to the nearest
   protein-coding transcription start site (TSS).
2. Summarizes delta H3K9me2 across TSS-distance bins in Eu and PCH.
3. Calculates TSS distance, local H3K9me2 signal, and TE expression for
   each annotated TE locus.
4. Summarizes TE expression across TSS-distance bins after separating
   loci with H3K9me2 gain/stability from loci with H3K9me2 loss.
5. Among expressed TE loci, compares local delta H3K9me2 between
   TSS-proximal loci (<2 kb) and TSS-distal loci (>20 kb) using a
   two-sided Mann-Whitney U test.

Required input files:
    H3K9me2_1kb_TE_correlation_results/H3K9_delta_TE_binned_1kb.csv
    w1118_v4_sorted.protein_coding.gtf
    w1118_TE-annotation_onecodetofindthemall_soloTE_chr.bed
    H3K9me2_sperm.RPGC.bw
    H3K9me2_wing.RPGC.bw
    1__spermatocyte.tsv.CPM.bw

The TE annotation coordinates are treated as 1-based inclusive,
matching the original analysis script.

Required Python packages:
    numpy
    pandas
    pyBigWig
    scipy
"""

from __future__ import annotations

import importlib.metadata
import sys
from pathlib import Path
from typing import Iterable

import numpy as np
import pandas as pd
import pyBigWig
from scipy.stats import mannwhitneyu


